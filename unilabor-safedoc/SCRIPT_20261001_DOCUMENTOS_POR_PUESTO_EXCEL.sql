       regexp_replace(btrim(d.title), '\s+', ' ', 'g') AS titulo_norm
  FROM public.documents d
 WHERE d.status = 'active';

-- Validaciones: aborta si algo no cuadra -------------------------------------
DO $$
DECLARE
  v_faltan_puestos TEXT;
  v_faltan_docs    TEXT;
  v_n              INT;
BEGIN
  SELECT string_agg(DISTINCT x.puesto_codigo, ', ')
    INTO v_faltan_puestos
    FROM (SELECT puesto_codigo FROM _matriz UNION SELECT puesto_codigo FROM _todos) x
   WHERE NOT EXISTS (SELECT 1 FROM public.rh_positions p
                      WHERE upper(p.code) = upper(x.puesto_codigo));
  IF v_faltan_puestos IS NOT NULL THEN
    RAISE EXCEPTION 'Puestos inexistentes en rh_positions: %', v_faltan_puestos;
  END IF;

  SELECT count(*), string_agg(DISTINCT m.documento, E'\n  ')
    INTO v_n, v_faltan_docs
    FROM _matriz m
   WHERE NOT EXISTS (SELECT 1 FROM _vigentes v WHERE v.titulo_norm = m.documento);
  IF v_n > 0 THEN
    RAISE EXCEPTION 'Documentos del Excel sin coincidencia vigente (% filas):%  %',
      v_n, E'\n', v_faltan_docs;
  END IF;
END $$;

-- Estado previo por puesto (para el reporte)
CREATE TEMP TABLE _antes ON COMMIT DROP AS
SELECT p.id AS position_id, count(pd.id) AS docs_antes
  FROM public.rh_positions p
  LEFT JOIN public.rh_position_documents pd ON pd.position_id = p.id
 GROUP BY p.id;

-- Pares a insertar: Excel (orden del archivo) + TODOS (orden por codigo) -----
CREATE TEMP TABLE _pares ON COMMIT DROP AS
SELECT p.id AS position_id, v.id AS document_id,
       min(m.orden) AS orden, 'EXCEL'::TEXT AS origen
  FROM _matriz m
  JOIN public.rh_positions p ON upper(p.code) = upper(m.puesto_codigo)
  JOIN _vigentes v ON v.titulo_norm = m.documento
 GROUP BY p.id, v.id
UNION ALL
SELECT p.id, v.id,
       row_number() OVER (PARTITION BY p.id ORDER BY COALESCE(v.code, v.title), v.title, v.id)::INT,
       'TODOS'
  FROM _todos t
  JOIN public.rh_positions p ON upper(p.code) = upper(t.puesto_codigo)
  CROSS JOIN _vigentes v;

INSERT INTO public.rh_position_documents (position_id, document_id, sort_order)
SELECT n.position_id, n.document_id,
       COALESCE((SELECT max(x.sort_order) FROM public.rh_position_documents x
                  WHERE x.position_id = n.position_id), 0)
       + row_number() OVER (PARTITION BY n.position_id ORDER BY n.orden, n.document_id)
  FROM _pares n
 WHERE NOT EXISTS (SELECT 1 FROM public.rh_position_documents e
                    WHERE e.position_id = n.position_id AND e.document_id = n.document_id)
ON CONFLICT (position_id, document_id) DO NOTHING;

-- Reporte -------------------------------------------------------------------
SELECT p.code AS puesto, p.name,
       a.docs_antes,
       (SELECT count(*) FROM public.rh_position_documents pd WHERE pd.position_id = p.id) - a.docs_antes AS agregados,
       (SELECT count(*) FROM public.rh_position_documents pd WHERE pd.position_id = p.id) AS docs_despues
  FROM public.rh_positions p
  JOIN _antes a ON a.position_id = p.id
 ORDER BY p.sort_order, p.code;

-- Titulos del Excel que coincidieron con mas de un documento vigente
SELECT m.documento, count(DISTINCT v.id) AS vigentes_con_ese_titulo
  FROM _matriz m JOIN _vigentes v ON v.titulo_norm = m.documento
 GROUP BY m.documento
HAVING count(DISTINCT v.id) > 1;

COMMIT;
